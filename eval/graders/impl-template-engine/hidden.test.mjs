for (const c of cases) {
  test(c.name, () => {
    const args = c.partials === undefined ? [c.template, c.view] : [c.template, c.view, c.partials];
    if (c.error !== undefined) {
      assert.throws(() => render(...args), (err) => err instanceof Error && err.message === c.error,
        `expected error ${JSON.stringify(c.error)}`);
    } else {
      assert.equal(render(...args), c.expected);
    }
  });
}

test("hidden suite has unique names", () => {
  assert.equal(new Set(cases.map((c) => c.name)).size, cases.length);
});

test("render does not mutate the view or partials", () => {
  const view = { a: [{ b: 1 }], c: { d: "x" } };
  const partials = { p: "{{d}}\n" };
  const before = JSON.stringify([view, partials]);
  render("{{#a}}{{b}}{{/a}}\n  {{#c}}\n  {{>p}}\n  {{/c}}\n", view, partials);
  assert.equal(JSON.stringify([view, partials]), before);
});

test("large template renders quickly", () => {
  const items = Array.from({ length: 20000 }, (_, i) => ({ i, name: `n<${i}>` }));
  const out = render("{{#items}}\n  <li>{{i}}: {{name}}</li>\n{{/items}}\n", { items });
  assert.equal(out.split("\n").length, 20001);
  assert.ok(out.startsWith("  <li>0: n&lt;0&gt;</li>\n"));
});
