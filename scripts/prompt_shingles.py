#!/usr/bin/env python3
"""Build or check the provenance fixture for our base prompts.

Our base prompts (crates/cyber-core/prompts/base/*.md) and any patch grammar
(crates/**/*.lark) are written clean-room. To keep them that way, the fixture lists
short hashes of every 12-word run ("shingle") of the reference product's text assets:
every .md, .lark and .txt under its codex-rs tree, and the text files of any assets,
templates or prompts folder. A test fails if any 12-word run of our assets hashes to
one of them. Only hashes are stored; the reference text is never vendored.

Normalization, mirrored by crates/cyber-core/tests/prompt_provenance.rs:
  * words are maximal runs of ASCII letters and digits, lowercased; everything else
    (punctuation, Markdown, non-ASCII) separates words;
  * a shingle is 12 consecutive words of one file joined by single spaces;
  * its hash is the first 12 hex digits of SHA-256 over the UTF-8 bytes.

Usage:
  python3 scripts/prompt_shingles.py generate <reference checkout>   # rewrite the fixture
  python3 scripts/prompt_shingles.py check                           # check our assets
Exit code 1 when `check` finds a match.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROMPTS = ROOT / "crates" / "cyber-core" / "prompts" / "base"
FIXTURE = ROOT / "crates" / "cyber-core" / "tests" / "fixtures" / "reference_prompt_shingles.txt"
WIDTH = 12
WORD_RE = re.compile(r"[A-Za-z0-9]+")


def words(text: str) -> list[str]:
    return [word.lower() for word in WORD_RE.findall(text)]


def shingle_hash(run: list[str]) -> str:
    return hashlib.sha256(" ".join(run).encode()).hexdigest()[:12]


def shingles(text: str) -> set[str]:
    run = words(text)
    return {shingle_hash(run[i : i + WIDTH]) for i in range(len(run) - WIDTH + 1)}


# Text assets of the reference checkout that can hold prompt, grammar or tool text.
SOURCE_TREE = "codex-rs"
SOURCE_SUFFIXES = {".md", ".lark", ".txt"}
ASSET_DIRS = {"assets", "templates", "prompts"}
ASSET_SUFFIXES = SOURCE_SUFFIXES | {".yaml", ".yml", ".toml", ".json"}
SKIPPED_DIRS = {"node_modules", "target", ".git"}


def is_reference_asset(relative: Path) -> bool:
    """Every .md, .lark and .txt under the source tree, plus the text files of any
    assets, templates or prompts folder elsewhere in the checkout."""
    folders = [part.lower() for part in relative.parts[:-1]]
    if SKIPPED_DIRS.intersection(folders):
        return False
    suffix = relative.suffix.lower()
    if folders[:1] == [SOURCE_TREE] and suffix in SOURCE_SUFFIXES:
        return True
    return suffix in ASSET_SUFFIXES and bool(ASSET_DIRS.intersection(folders))


def reference_files(checkout: Path) -> list[Path]:
    return [
        path
        for path in sorted(checkout.rglob("*"))
        if path.is_file() and is_reference_asset(path.relative_to(checkout))
    ]


def our_assets() -> list[Path]:
    """The prompt and grammar assets we ship: the base prompts and any grammar file."""
    crates = ROOT / "crates"
    grammars = [
        path
        for path in crates.rglob("*.lark")
        if not SKIPPED_DIRS.intersection(path.relative_to(crates).parts)
    ]
    return sorted(PROMPTS.glob("*.md")) + sorted(grammars)


def generate(checkout: Path) -> int:
    files = reference_files(checkout)
    if not files:
        print(f"no text assets under {checkout}", file=sys.stderr)
        return 1
    hashes: set[str] = set()
    for path in files:
        hashes |= shingles(path.read_text(encoding="utf-8", errors="replace"))
    header = (
        f"# SHA-256/12 of each normalized {WIDTH}-word shingle of {len(files)} reference\n"
        "# text assets (prompts, templates, grammars, tool text). Generated by\n"
        "# scripts/prompt_shingles.py; hashes only.\n"
    )
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(header + "".join(f"{h}\n" for h in sorted(hashes)))
    print(f"{len(hashes)} shingles from {len(files)} files -> {FIXTURE.relative_to(ROOT)}")
    return 0


def fixture_hashes() -> set[str]:
    lines = FIXTURE.read_text().splitlines()
    return {line for line in lines if line and not line.startswith("#")}


def matches(
    known: set[str] | None = None, assets: list[Path] | None = None
) -> list[tuple[str, str]]:
    """(file, 12-word run) pairs of our assets whose hash is in the fixture."""
    known = fixture_hashes() if known is None else known
    found = []
    for path in our_assets() if assets is None else assets:
        run = words(path.read_text(encoding="utf-8"))
        for i in range(len(run) - WIDTH + 1):
            window = run[i : i + WIDTH]
            if shingle_hash(window) in known:
                found.append((path.name, " ".join(window)))
    return found


def check() -> int:
    found = matches()
    for name, window in found:
        print(f"{name}: matches a reference prompt: {window!r}")
    return 1 if found else 0


def main(argv: list[str]) -> int:
    if len(argv) == 2 and argv[0] == "generate":
        return generate(Path(argv[1]))
    if argv == ["check"]:
        return check()
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
